// Package appleadapter implements only authenticated installation and exact
// readback through a host-supplied restricted stream dialer. It never launches.
package appleadapter

import (
	"bytes"
	"context"
	"crypto/tls"
	"crypto/x509"
	"encoding/binary"
	"encoding/pem"
	"errors"
	"fmt"
	"io"
	"net"
	"os"
	"sync"
	"time"

	"github.com/danielpaulus/go-ios/ios"
	"github.com/danielpaulus/go-ios/ios/afc"
	"howett.net/plist"
)

type Service string

const (
	Lockdown     Service = "lockdown"
	AFC          Service = "afc"
	Installation Service = "installation-proxy"
	maxPlist             = 2 * 1024 * 1024
	maxPackage           = int64(8 * 1024 * 1024 * 1024)
)

// Dial must bind every stream to the enrolled phone/session. Ports other than
// 62078 come solely from authenticated StartService replies for these two names.
// A broker must not turn this into a public caller-selected host/port API.
type Dial func(context.Context, Service, uint16) (net.Conn, error)
type PairRecord struct {
	HostID            string
	SystemBUID        string
	HostCertificate   []byte
	HostPrivateKey    []byte
	DeviceCertificate []byte
}
type Artifact struct {
	DeviceID          string `json:"deviceID"`
	BundleID          string `json:"bundleID"`
	Version           string `json:"version"`
	Build             string `json:"build"`
	Package           string `json:"package"`
	ForwarderBundleID string `json:"forwarderBundleID"`
}
type Result struct {
	Kind              string
	DefinitiveFailure bool
	Confirmed         bool
	HandedOff         bool
	Stage             string
	Err               error
}
type Adapter struct {
	Dial Dial
	Pair PairRecord
}

// Install accepts an immutable, signature/profile/digest-validated package from
// the Mac artifact store. The composition layer retains that evidence. A broken
// connection after handoff remains unknown; the next invocation reads back first.
func (a Adapter) Install(ctx context.Context, artifact Artifact) (r Result) {
	r.Stage = "preflight"
	defer func() {
		if r.Err != nil {
			r.Kind = failureKind(r.Err)
		}
	}()
	if a.Dial == nil || a.Pair.HostID == "" || a.Pair.SystemBUID == "" || artifact.DeviceID == "" || artifact.BundleID == "" || artifact.Version == "" || artifact.Build == "" || artifact.ForwarderBundleID == "" {
		r.Err = errors.New("incomplete artifact identity")
		return
	}
	if artifact.BundleID == artifact.ForwarderBundleID {
		r.Err = Failure{"unsupported", "self-update requires an independent installation path"}
		return
	}
	ctx, cancel := context.WithTimeout(ctx, 8*time.Minute)
	defer cancel()
	r.Stage = "before-readback"
	matched, err := a.readback(ctx, artifact)
	if err != nil {
		r.Err = err
		return
	}
	if matched {
		r.Confirmed = true
		return
	}
	r.Stage = "upload"
	f, err := os.Open(artifact.Package)
	if err != nil {
		r.Err = err
		return
	}
	defer f.Close()
	st, err := f.Stat()
	if err != nil {
		r.Err = err
		return
	}
	if !st.Mode().IsRegular() || st.Size() == 0 || st.Size() > maxPackage {
		r.Err = errors.New("invalid retained package size")
		return
	}
	socket, err := a.service(ctx, artifact.DeviceID, AFC)
	if err != nil {
		r.Err = err
		return
	}
	client := afc.NewFromConn(ios.NewDeviceConnectionWithConn(&afcBoundedConn{Conn: socket}))
	defer client.Close()
	// The name is generated by this process, never from a source path or bundle ID.
	destination := fmt.Sprintf("PublicStaging/orbit-%d.ipa", time.Now().UnixNano())
	if _, err = client.Stat("PublicStaging"); err != nil {
		err = client.MkDir("PublicStaging")
	}
	if err == nil {
		err = client.WriteToFile(io.LimitReader(f, st.Size()), destination)
	}
	if err != nil {
		r.Err = err
		return
	}
	defer client.Remove(destination)
	r.Stage = "installation-service"
	install, err := a.service(ctx, artifact.DeviceID, Installation)
	if err != nil {
		r.Err = err
		return
	}
	defer install.Close()
	request := map[string]any{"Command": "Install", "PackagePath": destination, "ClientOptions": map[string]any{"PackageType": "Developer"}}
	// Even partial transmission of Install may have reached the system daemon.
	r.Stage = "install"
	r.HandedOff = true
	if err = sendPlist(install, request); err != nil {
		r.Err = err
		return
	}
	complete := false
	for i := 0; i < 1024; i++ {
		reply, e := receivePlist(install)
		if e != nil {
			r.Err = e
			return
		}
		if failure, ok := reply["Error"].(string); ok {
			r.DefinitiveFailure = true
			kind := "unknown"
			switch failure {
			case "ApplicationVerificationFailed", "BundleVerificationFailed", "MismatchedApplicationIdentifierEntitlement", "MissingCodeSignature":
				kind = "signing"
			case "DeviceLocked", "PasswordProtected":
				kind = "locked"
			}
			r.Err = Failure{kind, "Apple installation failed: " + failure}
			return
		}
		if reply["Status"] == "Complete" {
			complete = true
			break
		}
	}
	if !complete {
		r.Err = errors.New("installation status limit reached")
		return
	}
	r.Stage = "readback"
	r.Confirmed, r.Err = a.readback(ctx, artifact)
	if r.Err == nil && !r.Confirmed {
		r.Err = errors.New("installed revision could not be confirmed")
	}
	return
}

func (a Adapter) readback(ctx context.Context, artifact Artifact) (bool, error) {
	socket, err := a.service(ctx, artifact.DeviceID, Installation)
	if err != nil {
		return false, err
	}
	defer socket.Close()
	if err = sendPlist(socket, map[string]any{"Command": "Lookup", "ClientOptions": map[string]any{"BundleIDs": []string{artifact.BundleID}, "ReturnAttributes": []string{"CFBundleIdentifier", "CFBundleShortVersionString", "CFBundleVersion"}}}); err != nil {
		return false, err
	}
	reply, err := receivePlist(socket)
	if err != nil {
		return false, err
	}
	if failure, ok := reply["Error"].(string); ok {
		return false, fmt.Errorf("Apple readback failed: %s", failure)
	}
	lookup, ok := reply["LookupResult"].(map[string]any)
	if !ok {
		return false, errors.New("missing installed application lookup")
	}
	app, ok := lookup[artifact.BundleID].(map[string]any)
	if !ok {
		return false, nil
	}
	return app["CFBundleIdentifier"] == artifact.BundleID && app["CFBundleShortVersionString"] == artifact.Version && app["CFBundleVersion"] == artifact.Build, nil
}
func (a Adapter) service(ctx context.Context, deviceID string, service Service) (net.Conn, error) {
	names := map[Service]string{AFC: "com.apple.afc", Installation: "com.apple.mobile.installation_proxy"}
	name, ok := names[service]
	if !ok {
		return nil, errors.New("unsupported Apple service")
	}
	socket, err := a.Dial(ctx, Lockdown, 62078)
	if err != nil {
		return nil, err
	}
	bound := newBoundConn(ctx, socket)
	defer func() {
		if bound != nil {
			bound.Close()
		}
	}()
	if err = sendPlist(bound, map[string]any{"Request": "StartSession", "Label": "Orbit", "ProtocolVersion": "2", "HostID": a.Pair.HostID, "SystemBUID": a.Pair.SystemBUID}); err != nil {
		return nil, err
	}
	reply, err := receivePlist(bound)
	if err != nil {
		return nil, err
	}
	if reply["EnableSessionSSL"] != true {
		return nil, Failure{"pairing", "Apple pairing did not establish a secure session"}
	}
	secure, err := a.secure(ctx, bound)
	if err != nil {
		return nil, err
	}
	// TLS certificate pinning and the actual UDID are both mandatory. A relay ID,
	// synchronized account key or claimed endpoint ID is not Apple device identity.
	if err = sendPlist(secure, map[string]any{"Request": "GetValue", "Label": "Orbit", "Key": "UniqueDeviceID"}); err != nil {
		return nil, err
	}
	reply, err = receivePlist(secure)
	if err != nil {
		return nil, err
	}
	if reply["Value"] != deviceID {
		return nil, Failure{"identity", "Apple physical device identity mismatch"}
	}
	if err = sendPlist(secure, map[string]any{"Request": "StartService", "Label": "Orbit", "Service": name}); err != nil {
		return nil, err
	}
	reply, err = receivePlist(secure)
	if err != nil {
		return nil, err
	}
	port, ok := reply["Port"].(uint64)
	if !ok || port == 0 || port > 65535 || port == 62078 {
		return nil, Failure{"identity", "invalid authenticated Apple service port"}
	}
	endpoint, err := a.Dial(ctx, service, uint16(port))
	if err != nil {
		return nil, err
	}
	result := newBoundConn(ctx, endpoint)
	if reply["EnableServiceSSL"] == true {
		secured, e := a.secure(ctx, result)
		if e != nil {
			result.Close()
			return nil, e
		}
		return secured, nil
	}
	return result, nil
}
func (a Adapter) secure(ctx context.Context, raw net.Conn) (*tls.Conn, error) {
	certificate, err := tls.X509KeyPair(a.Pair.HostCertificate, a.Pair.HostPrivateKey)
	if err != nil {
		return nil, Failure{"pairing", "invalid Mac host pairing identity"}
	}
	block, _ := pem.Decode(a.Pair.DeviceCertificate)
	expected := a.Pair.DeviceCertificate
	if block != nil {
		expected = block.Bytes
	}
	if _, err = x509.ParseCertificate(expected); err != nil {
		return nil, Failure{"pairing", "invalid paired Apple device certificate"}
	}
	conn := tls.Client(raw, &tls.Config{MinVersion: tls.VersionTLS12, Certificates: []tls.Certificate{certificate},
		// Apple pairing certificates have no public DNS name. Replace WebPKI name
		// validation with the exact existing paired device certificate, while Go still
		// verifies the TLS handshake signatures and proof of its private key.
		InsecureSkipVerify: true, VerifyConnection: func(state tls.ConnectionState) error {
			if len(state.PeerCertificates) == 0 || !bytes.Equal(state.PeerCertificates[0].Raw, expected) {
				return Failure{"identity", "paired Apple certificate mismatch"}
			}
			return nil
		}})
	handshake, cancel := context.WithTimeout(ctx, 20*time.Second)
	defer cancel()
	if err = conn.HandshakeContext(handshake); err != nil {
		return nil, err
	}
	return conn, nil
}
func sendPlist(w io.Writer, value map[string]any) error {
	data, err := plist.Marshal(value, plist.XMLFormat)
	if err != nil {
		return err
	}
	if len(data) > maxPlist {
		return errors.New("Apple message exceeds its limit")
	}
	header := make([]byte, 4)
	binary.BigEndian.PutUint32(header, uint32(len(data)))
	_, err = io.Copy(w, io.MultiReader(bytes.NewReader(header), bytes.NewReader(data)))
	return err
}
func receivePlist(r io.Reader) (map[string]any, error) {
	header := make([]byte, 4)
	if _, err := io.ReadFull(r, header); err != nil {
		return nil, err
	}
	size := binary.BigEndian.Uint32(header)
	if size == 0 || size > maxPlist {
		return nil, errors.New("Apple message exceeds its limit")
	}
	data := make([]byte, size)
	if _, err := io.ReadFull(r, data); err != nil {
		return nil, err
	}
	var value map[string]any
	_, err := plist.Unmarshal(data, &value)
	return value, err
}

type boundConn struct {
	net.Conn
	done chan struct{}
	once sync.Once
}

func newBoundConn(ctx context.Context, conn net.Conn) *boundConn {
	c := &boundConn{Conn: conn, done: make(chan struct{})}
	if deadline, ok := ctx.Deadline(); ok {
		conn.SetDeadline(deadline)
	}
	go func() {
		select {
		case <-ctx.Done():
			conn.Close()
		case <-c.done:
		}
	}()
	return c
}
func (c *boundConn) Close() error { c.once.Do(func() { close(c.done) }); return c.Conn.Close() }

// Guard the upstream AFC decoder before it allocates from device-controlled
// lengths. This adapter only needs small status/open/stat replies, not arbitrary
// filesystem downloads. Header bytes and payload never accumulate without bounds.
type afcBoundedConn struct {
	net.Conn
	header    []byte
	remaining uint64
	sequence  uint64
}

func (c *afcBoundedConn) Read(p []byte) (int, error) {
	if len(p) == 0 {
		return 0, nil
	}
	if len(c.header) == 0 && c.remaining == 0 {
		header := make([]byte, 40)
		if _, err := io.ReadFull(c.Conn, header); err != nil {
			return 0, err
		}
		whole := binary.LittleEndian.Uint64(header[8:16])
		head := binary.LittleEndian.Uint64(header[16:24])
		sequence := binary.LittleEndian.Uint64(header[24:32])
		operation := binary.LittleEndian.Uint64(header[32:40])
		if binary.LittleEndian.Uint64(header[:8]) != 0x4141504c36414643 || whole > 65536 || head < 40 || head > whole || sequence != c.sequence+1 || (operation != 1 && operation != 2 && operation != 14) || ((operation == 1 || operation == 14) && head < 48) {
			c.Conn.Close()
			return 0, errors.New("invalid or oversized AFC reply")
		}
		c.sequence = sequence
		c.header = header
		c.remaining = whole - 40
	}
	if len(c.header) > 0 {
		n := copy(p, c.header)
		c.header = c.header[n:]
		return n, nil
	}
	if uint64(len(p)) > c.remaining {
		p = p[:c.remaining]
	}
	n, err := c.Conn.Read(p)
	c.remaining -= uint64(n)
	return n, err
}

// Stable classes let the Mac distinguish route failure from a pairing, identity,
// signing or lock failure without blindly trying another transport.
type Failure struct{ Kind, Message string }

func (f Failure) Error() string { return f.Message }
func failureKind(err error) string {
	var failure Failure
	if errors.As(err, &failure) {
		return failure.Kind
	}
	if errors.Is(err, context.Canceled) {
		return "cancelled"
	}
	var transport net.Error
	if errors.As(err, &transport) || errors.Is(err, io.EOF) || errors.Is(err, io.ErrUnexpectedEOF) {
		return "transport"
	}
	var storage *os.PathError
	if errors.As(err, &storage) {
		return "storage"
	}
	return "unknown"
}
